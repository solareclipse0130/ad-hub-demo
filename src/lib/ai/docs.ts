const bigrams = (s: string) => {
  const t = s.replace(/\s+/g, "");
  return new Set(Array.from({ length: Math.max(t.length - 1, 0) }, (_, i) => t.slice(i, i + 2)));
};

export function searchDocs(query: string, k = 2) {
  const q = bigrams(query);
  return DOC_SECTIONS.map((s) => {
    const b = bigrams(s.title + s.body);
    return { ...s, score: [...q].filter((x) => b.has(x)).length };
  })
    .sort((a, b) => b.score - a.score)
    .slice(0, k)
    .map(({ title, body }) => ({ 出处: `使用说明 · ${title}`, 内容: body }));
}
